#!/usr/bin/env node
// Regenerates hero.ts: Kage's avatar (docs/kage-avatar.jpg) as braille, one colour class per cell.
//   node cli/make-hero.ts        (macOS: uses `sips` to scale the picture and write a BMP)
// Each cell is 2x4 dots. Highlights light every dot; the red field lights every other dot, a
// halftone like the poster. Classes: r red, w white, m muted, d dark, g gold.
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'

const SOURCE = new URL('../docs/kage-avatar.jpg', import.meta.url).pathname
const SIZES = { big: [46, 23], small: [32, 16] } as const
// bit of each dot in a braille cell: [dx, dy, bit]
const BITS = [[0, 0, 1], [0, 1, 2], [0, 2, 4], [1, 0, 8], [1, 1, 16], [1, 2, 32], [0, 3, 64], [1, 3, 128]] as const

function pixels(cols: number, rows: number) {
  const w = cols * 2, h = rows * 4
  const bmp = `${mkdtempSync(`${tmpdir()}/kage-hero-`)}/hero.bmp`
  execFileSync('sips', ['-z', String(h), String(w), '-s', 'format', 'bmp', SOURCE, '--out', bmp], { stdio: 'ignore' })
  const b = readFileSync(bmp)
  const at = b.readUInt32LE(10), bw = b.readInt32LE(18), bh = b.readInt32LE(22), bpp = b.readUInt16LE(28)
  if (bw !== w || Math.abs(bh) !== h || (bpp !== 24 && bpp !== 32)) throw new Error(`unexpected BMP ${bw}x${bh} at ${bpp} bits`)
  const stride = Math.floor((bpp * w + 31) / 32) * 4
  return (x: number, y: number): [number, number, number] => {
    const o = at + (bh > 0 ? h - 1 - y : y) * stride + x * (bpp / 8)
    return [b[o + 2]!, b[o + 1]!, b[o]!]
  }
}

function braille(cols: number, rows: number) {
  const px = pixels(cols, rows)
  const chars: string[] = [], cls: string[] = []
  for (let r = 0; r < rows; r++) {
    let line = '', k = ''
    for (let c = 0; c < cols; c++) {
      let bits = 0, sr = 0, sg = 0, sb = 0
      for (const [dx, dy, bit] of BITS) {
        const [R, G, B] = px(c * 2 + dx, r * 4 + dy)
        sr += R; sg += G; sb += B
        const lum = 0.3 * R + 0.59 * G + 0.11 * B
        if (lum > 110 || (R > 110 && R > G * 1.7 && (dx + dy) % 2 === 0)) bits |= bit
      }
      sr /= 8; sg /= 8; sb /= 8
      const lum = 0.3 * sr + 0.59 * sg + 0.11 * sb
      let cl = 'd'
      if (sr > 130 && sg > 100 && sb < 110 && sr - sb > 60 && sg - sb > 30) cl = 'g'
      else if (sr > 95 && sr > sg * 1.6) cl = 'r'
      else if (lum > 165) cl = 'w'
      else if (lum > 95) cl = 'm'
      // The avatar's gold script runs down its left edge: leave it out. Only the star stays gold.
      if (cl === 'g' && c < cols * 0.2) { cl = 'd'; bits = 0 }
      line += bits ? String.fromCharCode(0x2800 + bits) : ' '
      k += cl
    }
    chars.push(line); cls.push(k)
  }
  return { chars, cls }
}

const out = Object.entries(SIZES).map(([name, [c, r]]) => `export const HERO_${name.toUpperCase()} = ${JSON.stringify(braille(c, r), null, 1)}\n`)
writeFileSync(new URL('../core/hero.ts', import.meta.url), `// Generated by make-hero.ts from docs/kage-avatar.jpg. Do not edit: run \`node cli/make-hero.ts\`.\n// chars: braille per cell. cls: one colour class per cell (r red, w white, m muted, d dark, g gold).\n${out.join('')}`)
